def normalize_party(speaker_group: str) -> str:
    """speakerGroupの値を政党名に正規化する。マッピングに無い場合は元の値をそのまま返す。"""
    if not speaker_group:
        return "(不明)"
    return PARTY_MAPPING.get(speaker_group, speaker_group)
