"""
発言テキストのノイズ除去ユーティリティ。

国会会議録の speech フィールドから、分析に不要な定型句
(冒頭の名乗り・話者マーカー、末尾の御清聴・答弁締め・登壇ト書き・区切り線など)
を除去し、形態素解析に渡しやすい形に整形する。
"""

import re

_WS = r"[\u3000\s]*"  # 全角スペース・改行等をまとめて許容

# 末尾に繰り返し現れうる定型句・記号のパターン群
_TRAILING_PATTERNS = [
    r"[\u3000\s]*〔[^〕]*〕" + _WS + r"$",              # 登壇などのト書き
    r"[\u3000\s]*[─―]{3,}[◇◆]?" + _WS + r"$",          # 区切り線(末尾記号に対応)
    r"[\u3000\s]*御清聴.{0,10}?ありがとうございました。(（拍手）)?" + _WS + r"$",
    r"[\u3000\s]*ありがとうございました。（拍手）" + _WS + r"$",
    r"[\u3000\s]*残余の質問(については|につきましては)、関係大臣から答弁(を)?させます。(（拍手）)?" + _WS + r"$",
    r"[\u3000\s]*以上、御報告申し上げます。（拍手）" + _WS + r"$",
]


def clean_speech(text: str) -> str:
    """speechテキストからノイズを除去して返す。"""
    text = text.replace("\r\n", "\n")

    # 冒頭:話者マーカー「○(役職・氏名等)　」は、○の直後から最初の全角スペースまでを丸ごと除去
    text = re.sub(r"^○[^\u3000\n]*\u3000", "", text)

    # 冒頭:「(会派名の)氏名です。」という自己紹介文(あれば除去。委員長報告等にはない)
    if re.match(r"^.{0,30}?です。", text):
        text = re.sub(r"^.{0,30}?です。\n?", "", text, count=1)

    # 冒頭:答弁の定型句「○○議員の御質問にお答え(いた)?します。」
    text = re.sub(r"^\S+?議員の御質問にお答え(いた)?します。?\n?", "", text)

    # 末尾のノイズを、変化がなくなるまで繰り返し剥がしていく
    changed = True
    while changed:
        changed = False
        for pattern in _TRAILING_PATTERNS:
            new_text = re.sub(pattern, "", text)
            if new_text != text:
                text = new_text
                changed = True

    return text.strip()